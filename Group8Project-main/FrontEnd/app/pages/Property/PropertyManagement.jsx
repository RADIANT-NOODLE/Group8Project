
import React, { useCallback, useEffect, useMemo, useState } from "react";
import { Link } from "react-router-dom";
import DashboardSidebar from "../Dashboards/shared/DashboardSidebar";
import { getPropertiesForManagement } from "../../data/propertyStorage";
import "./PropertyManagement.css";

/*
=========================================================
VALORA PROPERTY MANAGEMENT
=========================================================

Frontend-only implementation.

Supports:
- Shared DashboardSidebar
- Search and filters
- Property statistics
- Loading, error and empty states
- Database/API-ready property records
- Property detail navigation

No sample properties are generated by this page.
=========================================================
*/

function getLocation(property) {
    if (typeof property?.location === "string") {
        return property.location;
    }

    if (property?.location && typeof property.location === "object") {
        return [
            property.location.address,
            property.location.suburb,
            property.location.city,
            property.location.province,
        ]
            .filter(Boolean)
            .join(", ");
    }

    if (typeof property?.address === "string") {
        return property.address;
    }

    return "Location not provided";
}

function getListingStatus(property) {
    const listing = property?.listing || {};

    const status = String(
        listing.listingStatus ||
        property?.listingStatus ||
        property?.status ||
        "Not Listed"
    ).trim();

    const approvalStatus = String(
        listing.hoaApprovalStatus ||
        property?.hoaApprovalStatus ||
        ""
    ).trim().toLowerCase();

    if (
        status.toLowerCase() === "published" &&
        approvalStatus &&
        approvalStatus !== "approved"
    ) {
        return "Pending HOA Approval";
    }

    return status;
}

function getListingPrice(property) {
    const listing = property?.listing || {};

    const listingType = String(
        listing.listingType ||
        property?.listingType ||
        ""
    ).toLowerCase();

    const price =
        listing.askingPrice ??
        property?.askingPrice ??
        listing.rentalPrice ??
        property?.rentalPrice ??
        listing.price ??
        property?.price;

    if (
        price === undefined ||
        price === null ||
        price === ""
    ) {
        return null;
    }

    const numericPrice = Number(price);

    if (!Number.isFinite(numericPrice)) {
        return null;
    }

    const formattedPrice = new Intl.NumberFormat("en-ZA", {
        style: "currency",
        currency: "ZAR",
        maximumFractionDigits: 0,
    }).format(numericPrice);

    const isRental =
        listingType.includes("rent") ||
        listing.rentalPrice !== undefined ||
        property?.rentalPrice !== undefined;

    return isRental
        ? `${formattedPrice} / month`
        : formattedPrice;
}

function getPropertyType(property) {
    return (
        property?.propertyType ||
        property?.type ||
        property?.listing?.propertyType ||
        "Property"
    );
}

function getPropertyImage(property) {
    if (typeof property?.image === "string") {
        return property.image;
    }

    if (typeof property?.imageUrl === "string") {
        return property.imageUrl;
    }

    if (typeof property?.imageURL === "string") {
        return property.imageURL;
    }

    if (typeof property?.photo === "string") {
        return property.photo;
    }

    if (
        Array.isArray(property?.images) &&
        typeof property.images[0] === "string"
    ) {
        return property.images[0];
    }

    return null;
}

function getStatusClass(status) {
    return String(status)
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-|-$/g, "");
}

function PropertyManagement() {
    const [properties, setProperties] = useState([]);
    const [searchTerm, setSearchTerm] = useState("");
    const [statusFilter, setStatusFilter] = useState("All");
    const [typeFilter, setTypeFilter] = useState("All");
    const [loading, setLoading] = useState(true);
    const [error, setError] = useState("");

    /*
    =========================================================
    LOAD PROPERTY RECORDS
    =========================================================
    */

    const loadProperties = useCallback(async () => {
        setLoading(true);
        setError("");

        try {
            const records = await getPropertiesForManagement();

            if (!Array.isArray(records)) {
                throw new Error(
                    "The property data source returned an invalid response."
                );
            }

            setProperties(records);
        } catch (err) {
            console.error(
                "Unable to load property records:",
                err
            );

            setProperties([]);

            setError(
                "We couldn't load property records. Please try again."
            );
        } finally {
            setLoading(false);
        }
    }, []);

    useEffect(() => {
        loadProperties();
    }, [loadProperties]);

    /*
    =========================================================
    FILTER OPTIONS
    =========================================================
    */

    const propertyTypes = useMemo(() => {
        return [
            ...new Set(
                properties.map(getPropertyType).filter(Boolean)
            ),
        ].sort();
    }, [properties]);

    const propertyStatuses = useMemo(() => {
        return [
            ...new Set(
                properties.map(getListingStatus).filter(Boolean)
            ),
        ].sort();
    }, [properties]);

    /*
    =========================================================
    FILTERED PROPERTY RECORDS
    =========================================================
    */

    const filteredProperties = useMemo(() => {
        const search = searchTerm.trim().toLowerCase();

        return properties.filter(property => {
            const id = String(property?.id || "").toLowerCase();

            const name = String(
                property?.name ||
                property?.title ||
                property?.unitName ||
                ""
            ).toLowerCase();

            const location = getLocation(property).toLowerCase();

            const type = getPropertyType(property).toLowerCase();

            const status = getListingStatus(property);

            const matchesSearch =
                !search ||
                id.includes(search) ||
                name.includes(search) ||
                location.includes(search) ||
                type.includes(search);

            const matchesStatus =
                statusFilter === "All" ||
                status === statusFilter;

            const matchesType =
                typeFilter === "All" ||
                getPropertyType(property) === typeFilter;

            return (
                matchesSearch &&
                matchesStatus &&
                matchesType
            );
        });
    }, [
        properties,
        searchTerm,
        statusFilter,
        typeFilter,
    ]);

    /*
    =========================================================
    STATISTICS
    =========================================================
    */

    const totalProperties = properties.length;

    const publishedProperties = properties.filter(
        property =>
            getListingStatus(property).toLowerCase() === "published"
    ).length;

    const pendingProperties = properties.filter(property => {
        const status = getListingStatus(property).toLowerCase();

        return (
            status.includes("pending") ||
            status === "draft" ||
            status === "assigned"
        );
    }).length;

    /*
    =========================================================
    RENDER
    =========================================================
    */

    return (
        <div className="property-management-page">
            <DashboardSidebar />

            <main className="property-management-main">
                <header className="property-management-header">
                    <div>
                        <p className="property-management-eyebrow">
                            VALORA / PROPERTY MANAGEMENT
                        </p>

                        <h1>Property Management</h1>

                        <p className="property-management-subtitle">
                            View and manage property records across
                            the community.
                        </p>
                    </div>

                    <button
                        type="button"
                        className="property-refresh-button"
                        onClick={loadProperties}
                        disabled={loading}
                    >
                        <span aria-hidden="true">↻</span>
                        {loading ? "Loading..." : "Refresh"}
                    </button>
                </header>

                {/* PROPERTY STATISTICS */}

                <section
                    className="property-management-stats"
                    aria-label="Property statistics"
                >
                    <div className="property-stat-card">
                        <div className="property-stat-icon">
                            <span aria-hidden="true">⌂</span>
                        </div>

                        <div>
                            <p>Total Properties</p>
                            <h2>{totalProperties}</h2>
                            <span>All available records</span>
                        </div>
                    </div>

                    <div className="property-stat-card">
                        <div className="property-stat-icon published-icon">
                            <span aria-hidden="true">✓</span>
                        </div>

                        <div>
                            <p>Published Listings</p>
                            <h2>{publishedProperties}</h2>
                            <span>Approved and published</span>
                        </div>
                    </div>

                    <div className="property-stat-card">
                        <div className="property-stat-icon pending-icon">
                            <span aria-hidden="true">◷</span>
                        </div>

                        <div>
                            <p>Awaiting Action</p>
                            <h2>{pendingProperties}</h2>
                            <span>Pending, assigned or draft</span>
                        </div>
                    </div>
                </section>

                {/* SEARCH AND FILTERS */}

                <section className="property-management-toolbar">
                    <div className="property-search">
                        <span
                            className="property-search-icon"
                            aria-hidden="true"
                        >
                            ⌕
                        </span>

                        <input
                            type="search"
                            aria-label="Search properties"
                            placeholder="Search by property ID, name or location..."
                            value={searchTerm}
                            onChange={event =>
                                setSearchTerm(event.target.value)
                            }
                        />
                    </div>

                    <div className="property-filter">
                        <label htmlFor="property-status-filter">
                            Status
                        </label>

                        <select
                            id="property-status-filter"
                            value={statusFilter}
                            onChange={event =>
                                setStatusFilter(event.target.value)
                            }
                        >
                            <option value="All">All statuses</option>

                            {propertyStatuses.map(status => (
                                <option key={status} value={status}>
                                    {status}
                                </option>
                            ))}
                        </select>
                    </div>

                    <div className="property-filter">
                        <label htmlFor="property-type-filter">
                            Property Type
                        </label>

                        <select
                            id="property-type-filter"
                            value={typeFilter}
                            onChange={event =>
                                setTypeFilter(event.target.value)
                            }
                        >
                            <option value="All">All types</option>

                            {propertyTypes.map(type => (
                                <option key={type} value={type}>
                                    {type}
                                </option>
                            ))}
                        </select>
                    </div>
                </section>

                {/* RESULTS HEADER */}

                <section className="property-results-section">
                    <div className="property-results-header">
                        <div>
                            <h2>Property Records</h2>

                            <p>
                                {loading
                                    ? "Retrieving property records..."
                                    : `${filteredProperties.length} ${
                                        filteredProperties.length === 1
                                            ? "property"
                                            : "properties"
                                    } found`}
                            </p>
                        </div>
                    </div>

                    {/* LOADING STATE */}

                    {loading && (
                        <div
                            className="property-state-card"
                            role="status"
                        >
                            <div className="property-loading-spinner" />

                            <h3>Loading properties</h3>

                            <p>
                                Please wait while property records are
                                retrieved.
                            </p>
                        </div>
                    )}

                    {/* ERROR STATE */}

                    {!loading && error && (
                        <div
                            className="property-state-card property-error-state"
                            role="alert"
                        >
                            <div className="property-empty-icon">
                                !
                            </div>

                            <h3>Unable to load properties</h3>

                            <p>{error}</p>

                            <button
                                type="button"
                                className="property-primary-button"
                                onClick={loadProperties}
                            >
                                Try Again
                            </button>
                        </div>
                    )}

                    {/* EMPTY STATE: NO DATABASE RECORDS */}

                    {!loading &&
                        !error &&
                        properties.length === 0 && (
                            <div className="property-state-card">
                                <div className="property-empty-icon">
                                    <span aria-hidden="true">⌂</span>
                                </div>

                                <h3>No property records found</h3>

                                <p>
                                    Property records will appear here
                                    once they are available from the
                                    VALORA database.
                                </p>
                            </div>
                        )}

                    {/* EMPTY STATE: FILTERS RETURN NO MATCHES */}

                    {!loading &&
                        !error &&
                        properties.length > 0 &&
                        filteredProperties.length === 0 && (
                            <div className="property-state-card">
                                <div className="property-empty-icon">
                                    <span aria-hidden="true">⌕</span>
                                </div>

                                <h3>No matching properties</h3>

                                <p>
                                    Try changing your search term or
                                    selected filters.
                                </p>

                                <button
                                    type="button"
                                    className="property-secondary-button"
                                    onClick={() => {
                                        setSearchTerm("");
                                        setStatusFilter("All");
                                        setTypeFilter("All");
                                    }}
                                >
                                    Clear Filters
                                </button>
                            </div>
                        )}

                    {/* PROPERTY CARDS: ONLY REAL RECORDS RETURNED */}

                    {!loading &&
                        !error &&
                        filteredProperties.length > 0 && (
                            <div className="property-management-grid">
                                {filteredProperties.map(
                                    (property, index) => {
                                        const propertyId = property?.id;

                                        const title =
                                            property?.name ||
                                            property?.title ||
                                            property?.unitName ||
                                            `Property ${propertyId || index + 1}`;

                                        const image =
                                            getPropertyImage(property);

                                        const status =
                                            getListingStatus(property);

                                        const price =
                                            getListingPrice(property);

                                        return (
                                            <article
                                                className="managed-property-card"
                                                key={
                                                    propertyId ||
                                                    `property-${index}`
                                                }
                                            >
                                                <div className="managed-property-image">
                                                    {image ? (
                                                        <img
                                                            src={image}
                                                            alt={title}
                                                        />
                                                    ) : (
                                                        <div className="managed-property-image-placeholder">
                                                            <span aria-hidden="true">
                                                                ⌂
                                                            </span>

                                                            <p>
                                                                No image available
                                                            </p>
                                                        </div>
                                                    )}

                                                    <span
                                                        className={`property-status-badge status-${getStatusClass(
                                                            status
                                                        )}`}
                                                    >
                                                        {status}
                                                    </span>
                                                </div>

                                                <div className="managed-property-content">
                                                    <div className="managed-property-title-row">
                                                        <div>
                                                            <h3>{title}</h3>

                                                            <p className="managed-property-id">
                                                                ID: {propertyId || "Not assigned"}
                                                            </p>
                                                        </div>
                                                    </div>

                                                    <p className="managed-property-location">
                                                        <span aria-hidden="true">
                                                            ⌖
                                                        </span>

                                                        {getLocation(property)}
                                                    </p>

                                                    <div className="managed-property-details">
                                                        <span>
                                                            {getPropertyType(property)}
                                                        </span>

                                                        {property?.bedrooms != null && (
                                                            <span>
                                                                {property.bedrooms} bed
                                                            </span>
                                                        )}

                                                        {property?.bathrooms != null && (
                                                            <span>
                                                                {property.bathrooms} bath
                                                            </span>
                                                        )}

                                                        {property?.size != null && (
                                                            <span>
                                                                {property.size} m²
                                                            </span>
                                                        )}
                                                    </div>

                                                    <div className="managed-property-footer">
                                                        <div>
                                                            <span className="managed-property-price-label">
                                                                {price
                                                                    ? "Listing Price"
                                                                    : "Listing Price"}
                                                            </span>

                                                            <strong>
                                                                {price || "Not specified"}
                                                            </strong>
                                                        </div>

                                                        {propertyId ? (
                                                            <Link
                                                                className="property-view-button"
                                                                to={`/property/${encodeURIComponent(
                                                                    String(propertyId)
                                                                )}`}
                                                            >
                                                                View Details
                                                                <span aria-hidden="true">
                                                                    →
                                                                </span>
                                                            </Link>
                                                        ) : (
                                                            <button
                                                                type="button"
                                                                className="property-view-button"
                                                                disabled
                                                            >
                                                                View Details
                                                            </button>
                                                        )}
                                                    </div>
                                                </div>
                                            </article>
                                        );
                                    }
                                )}
                            </div>
                        )}
                </section>
            </main>
        </div>
    );
}

export default PropertyManagement;
